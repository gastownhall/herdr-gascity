// Third-party license notices for the code the mod bundles (design §9): every
// runtime dependency in package.json, with its exact LICENSE text. Written to
// gascity/THIRD_PARTY_NOTICES.md so the notices ship in the mod folder; a unit
// test keeps the committed file equal to this output.
//
// Usage: bun run scripts/notices.ts

import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

export const NOTICES_FILE = "gascity/THIRD_PARTY_NOTICES.md";
const ROOT = join(import.meta.dir, "..");

interface Pkg {
  name: string;
  version: string;
  license?: string;
  dependencies?: Record<string, string>;
}

/** The notices text for `root`'s runtime dependencies, from node_modules. */
export async function noticesText(root: string = ROOT): Promise<string> {
  const pkg = JSON.parse(await readFile(join(root, "package.json"), "utf8")) as Pkg;
  const out = [
    "# Third-party notices",
    "",
    "Packages the mod's source depends on at run time; esbuild bundles the parts `main.js` uses into it.",
    "Generated by `bun run notices` from package.json and node_modules; do not edit.",
    "",
  ];
  for (const name of Object.keys(pkg.dependencies ?? {}).sort()) {
    const dir = join(root, "node_modules", name);
    const dep = JSON.parse(await readFile(join(dir, "package.json"), "utf8")) as Pkg;
    const license = (await readFile(join(dir, "LICENSE"), "utf8")).trim();
    out.push(`## ${dep.name} ${dep.version} (${dep.license ?? "see below"})`, "", "```text", license, "```", "");
  }
  return out.join("\n");
}

if (import.meta.main) {
  await writeFile(join(ROOT, NOTICES_FILE), await noticesText());
  console.log(`wrote ${NOTICES_FILE}`);
}
