// Generates the mod's typed gc models from the pinned spec (design §4, §5.2):
//
//   src/gc/types.gen.ts       TypeScript types of the decoded models
//   src/gc/schemas.gen.ts     zod/mini schemas that decode them (imported via src/gc/zod.ts)
//   src/gc/operations.gen.ts  per-operation metadata (method, path, headers gc declares,
//                             success status, response schema) and typed path/query/body
//
// Only the operations and model fields in api/used-surface.json are generated.
// Decode policy (design §5.2):
//   - unknown extra fields are ignored (zod objects strip them);
//   - a missing required field or a wrong type is a decode error;
//   - a string enum in a response decodes an unknown value to {kind:"unrecognized", raw};
//   - gc's ["array","null"] (Go nil slices) decodes null to [] (absent too, when optional);
//   - constraints (format, minimum, pattern) are left to the ajv contract test.
//
// Usage: bun run scripts/gen-gc.ts [--check]

import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import {
  PINNED_SPEC, ROOT, USED_SURFACE, operationsById, readJson, refName, requestBody, successResponse,
  type LocatedOperation, type Parameter, type Schema, type Spec, type UsedSurface,
} from "./gc-spec.ts";

export const OUTPUTS = {
  types: "src/gc/types.gen.ts",
  schemas: "src/gc/schemas.gen.ts",
  operations: "src/gc/operations.gen.ts",
} as const;

/** The problem+json model every error response uses; always decoded. */
export const PROBLEM_MODEL = "ErrorModel";

const HEADER =
  "// Generated by scripts/gen-gc.ts from api/openapi.pinned.json and api/used-surface.json.\n" +
  "// Do not edit: change the used surface or re-pin, then run `bun run gen:gc`.\n";

type Side = "response" | "request";

/** A projected model: its listed fields with their resolved schemas. */
interface Field {
  name: string;
  schema: Schema;
  required: boolean;
  /** Decoded element by element by the client: emitted as unknown[]. */
  itemLevel: boolean;
}

interface Model {
  name: string;
  side: Side;
  fields: Field[];
  item: string | null;
}

class Generator {
  private readonly models = new Map<string, Model>();
  private readonly order: string[] = [];
  private readonly listed: Set<string>;

  constructor(private readonly spec: Spec, private readonly used: UsedSurface) {
    this.listed = new Set(Object.keys(used.models));
  }

  private component(name: string): Schema {
    const schema = this.spec.components.schemas[name];
    if (!schema) throw new Error(`no component schema ${name} in the pin`);
    return schema;
  }

  /** True for a component that is an object model (projected), false for a scalar (inlined). */
  private isObjectModel(name: string): boolean {
    const s = this.component(name);
    return s.type === "object" || s.oneOf !== undefined;
  }

  /** Projects a component to its listed fields and records it, dependencies first. */
  model(name: string, side: Side): void {
    const seen = this.models.get(name);
    if (seen) {
      if (seen.side !== side) throw new Error(`${name} is used both as a request and a response model`);
      return;
    }
    const entry = this.used.models[name];
    if (!entry) throw new Error(`${name} is reached from a used operation but not listed in ${USED_SURFACE}`);
    const schema = this.component(name);
    const props = schema.oneOf ? this.mergeVariants(name, schema.oneOf) : this.properties(schema);
    const fields: Field[] = entry.fields.map((field) => {
      const p = props.get(field);
      if (!p) throw new Error(`${name}.${field} is listed in ${USED_SURFACE} but not in the pin`);
      return { name: field, schema: p.schema, required: p.required, itemLevel: entry.itemLevel === field };
    });
    let item: string | null = null;
    if (entry.itemLevel) {
      const f = fields.find((x) => x.itemLevel);
      const ref = f?.schema.items?.$ref;
      if (!f || !ref) throw new Error(`${name}.itemLevel must name a listed array-of-$ref field`);
      item = refName(ref);
    }
    const model: Model = { name, side, fields, item };
    this.models.set(name, model);
    for (const f of fields) this.dependencies(f.schema, side);
    this.order.push(name);
  }

  private properties(schema: Schema): Map<string, { schema: Schema; required: boolean }> {
    const required = new Set(schema.required ?? []);
    return new Map(Object.entries(schema.properties ?? {}).map(([k, v]) => [k, { schema: v, required: required.has(k) }]));
  }

  /**
   * A oneOf of object variants (gc's typed event envelope) projects to the
   * fields the variants share: the same schema where they agree, string where
   * they are all strings (a const per variant), else unknown. Required only
   * when every variant requires it.
   */
  private mergeVariants(name: string, variants: Schema[]): Map<string, { schema: Schema; required: boolean }> {
    const props = variants.map((v) => {
      if (!v.$ref) throw new Error(`${name}: oneOf variants must be $refs`);
      return this.properties(this.component(refName(v.$ref)));
    });
    const names = new Set(props.flatMap((p) => [...p.keys()]));
    const out = new Map<string, { schema: Schema; required: boolean }>();
    for (const field of names) {
      const all = props.map((p) => p.get(field));
      const present = all.filter((x): x is { schema: Schema; required: boolean } => x !== undefined);
      const required = present.length === all.length && present.every((x) => x.required);
      const shapes = new Set(present.map((x) => shapeKey(x.schema)));
      let schema: Schema;
      if (shapes.size === 1) schema = present[0]!.schema;
      else if (present.every((x) => x.schema.type === "string")) schema = { type: "string" };
      else schema = {};
      out.set(field, { schema, required });
    }
    return out;
  }

  private dependencies(schema: Schema, side: Side): void {
    if (schema.$ref) {
      const name = refName(schema.$ref);
      if (this.isObjectModel(name)) this.model(name, side);
      else this.dependencies(this.component(name), side);
      return;
    }
    if (schema.items) this.dependencies(schema.items, side);
    if (schema.additionalProperties && typeof schema.additionalProperties === "object") {
      this.dependencies(schema.additionalProperties, side);
    }
  }

  checkAllListedUsed(): void {
    const unused = [...this.listed].filter((n) => !this.models.has(n));
    if (unused.length > 0) throw new Error(`listed in ${USED_SURFACE} but reached by no used operation: ${unused.join(", ")}`);
  }

  /** Models in dependency order. */
  ordered(): Model[] {
    return this.order.map((n) => this.models.get(n)!);
  }

  // ---- TypeScript types --------------------------------------------------

  tsType(schema: Schema, side: Side): string {
    if (schema.$ref) {
      const name = refName(schema.$ref);
      return this.isObjectModel(name) ? name : this.tsType(this.component(name), side);
    }
    const type = schema.type;
    if (Array.isArray(type)) {
      if (type.length === 2 && type.includes("array") && type.includes("null")) {
        return `${this.tsType(schema.items ?? {}, side)}[]`;
      }
      throw new Error(`unsupported type union ${JSON.stringify(type)}`);
    }
    switch (type) {
      case undefined:
        return "unknown";
      case "string":
        if (schema.enum) {
          const union = (schema.enum as string[]).map((v) => JSON.stringify(v)).join(" | ");
          return side === "response" ? `Drift<${union}>` : union;
        }
        return "string";
      case "integer":
      case "number":
        return "number";
      case "boolean":
        return "boolean";
      case "array":
        return `${this.tsType(schema.items ?? {}, side)}[]`;
      case "object":
        if (schema.properties) throw new Error("inline object schemas are not supported; give them a component");
        if (schema.additionalProperties && typeof schema.additionalProperties === "object") {
          return `Record<string, ${this.tsType(schema.additionalProperties, side)}>`;
        }
        return "Record<string, unknown>";
      default:
        throw new Error(`unsupported type ${String(type)}`);
    }
  }

  types(): string {
    const out = [HEADER, 'import type { Drift } from "./decode.ts";', ""];
    for (const m of this.ordered()) {
      const what = m.side === "response" ? "decoded from gc's" : "sent as gc's";
      out.push(`/** The fields of ${m.name} this mod uses, ${what} ${m.name}. */`);
      out.push(`export interface ${m.name} {`);
      for (const f of m.fields) {
        if (f.itemLevel) {
          out.push(`  /** Raw elements; the client decodes each one (item-level decode errors). */`);
          out.push(`  ${f.name}: unknown[];`);
        } else if (isNullableList(f.schema) && m.side === "response") {
          out.push(`  ${f.name}: ${this.tsType(f.schema, m.side)};`);
        } else if (f.required) {
          out.push(`  ${f.name}: ${this.tsType(f.schema, m.side)};`);
        } else {
          out.push(`  ${f.name}?: ${this.tsType(f.schema, m.side)}${m.side === "response" ? " | undefined" : ""};`);
        }
      }
      out.push("}", "");
    }
    return out.join("\n");
  }

  // ---- zod schemas -------------------------------------------------------

  zod(schema: Schema): string {
    if (schema.$ref) {
      const name = refName(schema.$ref);
      return this.isObjectModel(name) ? `${name}Schema` : this.zod(this.component(name));
    }
    const type = schema.type;
    if (Array.isArray(type)) {
      if (isNullableList(schema)) return `nullableList(${this.zod(schema.items ?? {})})`;
      throw new Error(`unsupported type union ${JSON.stringify(type)}`);
    }
    switch (type) {
      case undefined:
        return "z.unknown()";
      case "string":
        return schema.enum ? `enumOf(${JSON.stringify(schema.enum)})` : "z.string()";
      case "integer":
        return "z.int()";
      case "number":
        return "z.number()";
      case "boolean":
        return "z.boolean()";
      case "array":
        return `z.array(${this.zod(schema.items ?? {})})`;
      case "object":
        if (schema.additionalProperties && typeof schema.additionalProperties === "object") {
          return `z.record(z.string(), ${this.zod(schema.additionalProperties)})`;
        }
        return "z.record(z.string(), z.unknown())";
      default:
        throw new Error(`unsupported type ${String(type)}`);
    }
  }

  schemas(): string {
    const out = [
      HEADER,
      "// zod comes only from ./zod.ts, which turns on jitless before this module's",
      "// schemas are built (design §4).",
      'import * as z from "./zod.ts";',
      'import { enumOf, nullableList, optionalNullableList } from "./decode.ts";',
      'import type * as T from "./types.gen.ts";',
      "",
    ];
    for (const m of this.ordered()) {
      if (m.side !== "response") continue;
      out.push(`export const ${m.name}Schema: z.ZodMiniType<T.${m.name}> = z.object({`);
      for (const f of m.fields) {
        let expr: string;
        const list = f.required ? "nullableList" : "optionalNullableList";
        if (f.itemLevel) expr = `${list}(z.unknown())`;
        else if (isNullableList(f.schema)) expr = `${list}(${this.zod(f.schema.items ?? {})})`;
        else expr = f.required ? this.zod(f.schema) : `z.optional(${this.zod(f.schema)})`;
        out.push(`  ${f.name}: ${expr},`);
      }
      out.push("});", "");
    }
    return out.join("\n");
  }

  // ---- operations --------------------------------------------------------

  operations(ops: [string, LocatedOperation][]): string {
    const meta: string[] = [];
    const types: string[] = [];
    for (const [id, { path, method, op }] of ops) {
      const params = op.parameters ?? [];
      const headers = params.filter((p) => p.in === "header").map((p) => p.name);
      const unknownHeaders = headers.filter((h) => h !== "X-GC-Request" && h !== "Idempotency-Key");
      if (unknownHeaders.length > 0) throw new Error(`${id}: unhandled header parameters ${unknownHeaders.join(", ")}`);
      const csrf = params.some((p) => p.in === "header" && p.name === "X-GC-Request" && p.required === true);
      const idempotencyKey = headers.includes("Idempotency-Key");
      const pathParams = params.filter((p) => p.in === "path").map((p) => p.name);
      const success = successResponse(op);
      const responseModel = refName(success.schema.$ref ?? "");
      const body = requestBody(op);
      const bodyModel = body ? refName(body.schema.$ref ?? "") : null;
      const item = this.models.get(responseModel)?.item ?? null;

      meta.push(
        `  ${JSON.stringify(id)}: {`,
        `    method: ${JSON.stringify(method.toUpperCase())},`,
        `    path: ${JSON.stringify(path)},`,
        `    pathParams: ${JSON.stringify(pathParams)},`,
        `    csrf: ${csrf},`,
        `    idempotencyKey: ${idempotencyKey},`,
        `    body: ${bodyModel ? JSON.stringify(bodyModel) : "null"},`,
        `    success: ${success.status},`,
        `    response: S.${responseModel}Schema,`,
        `    item: ${item ? `S.${item}Schema` : "null"},`,
        `  },`,
      );
      const query = params.filter((p) => p.in === "query").map((p) => this.queryField(p)).join(" ");
      const pathType = params.filter((p) => p.in === "path")
        .map((p) => `${p.name}: ${this.tsType(p.schema ?? { type: "string" }, "request")};`).join(" ");
      const bodyType = bodyModel ? (body!.required ? `T.${bodyModel}` : `T.${bodyModel} | undefined`) : "undefined";
      const decoded = item ? `Listed<T.${responseModel}, T.${item}>` : `T.${responseModel}`;
      types.push(
        `  ${JSON.stringify(id)}: {`,
        `    path: ${pathType ? `{ ${pathType} }` : "{}"};`,
        `    query: ${query ? `{ ${query} }` : "{}"};`,
        `    body: ${bodyType};`,
        `    decoded: ${decoded};`,
        `  };`,
      );
    }
    return [
      HEADER,
      'import type { Listed } from "./decode.ts";',
      'import * as S from "./schemas.gen.ts";',
      'import type * as T from "./types.gen.ts";',
      "",
      "/**",
      " * Every gc operation the mod calls, from the pin: `csrf` = gc requires X-GC-Request;",
      " * `idempotencyKey` = gc declares Idempotency-Key (sent only then, design §7.3);",
      " * `item` = the list elements are decoded one by one.",
      " */",
      "export const OPERATIONS = {",
      ...meta,
      "} as const;",
      "",
      "/** A used gc operationId. */",
      "export type OperationId = keyof typeof OPERATIONS;",
      "",
      "/** Typed path and query parameters, request body and decoded response per operation. */",
      "export interface OperationTypes {",
      ...types,
      "}",
      "",
    ].join("\n");
  }

  private queryField(p: Parameter): string {
    const schema = p.schema ?? {};
    let type: string;
    if (isNullableList(schema) || schema.type === "array") type = `readonly ${this.tsType(schema.items ?? {}, "request")}[]`;
    else type = this.tsType(schema, "request");
    return `${JSON.stringify(p.name)}${p.required ? "" : "?"}: ${type};`;
  }
}

/** gc's Go nil slice: ["array","null"]. */
function isNullableList(schema: Schema): boolean {
  return Array.isArray(schema.type) && schema.type.length === 2 && schema.type.includes("array") && schema.type.includes("null");
}

const IGNORED_FOR_SHAPE = new Set([
  "description", "title", "examples", "example", "const", "not", "enum", "format", "minimum", "maximum",
  "default", "minLength", "maxLength", "pattern",
]);

/** A schema's structure without docs and value constraints, for comparing oneOf variants. */
function shapeKey(schema: unknown): string {
  return JSON.stringify(schema, (key, value) => (IGNORED_FOR_SHAPE.has(key) ? undefined : value));
}

/** Generates the three files' contents. */
export function generate(spec: Spec, used: UsedSurface): Record<keyof typeof OUTPUTS, string> {
  const g = new Generator(spec, used);
  const byId = operationsById(spec);
  const ops = Object.keys(used.operations).map((id): [string, LocatedOperation] => {
    const located = byId.get(id);
    if (!located) throw new Error(`operation ${id} is not in the pin`);
    return [id, located];
  });
  g.model(PROBLEM_MODEL, "response");
  for (const [id, { op }] of ops) {
    const success = successResponse(op);
    if (!success.schema.$ref) throw new Error(`${id}: the success response must be a $ref`);
    g.model(refName(success.schema.$ref), "response");
    const body = requestBody(op);
    if (body) {
      if (!body.schema.$ref) throw new Error(`${id}: the request body must be a $ref`);
      g.model(refName(body.schema.$ref), "request");
    }
  }
  for (const name of used.payloadModels) g.model(name, "response");
  g.checkAllListedUsed();
  return { types: g.types(), schemas: g.schemas(), operations: g.operations(ops) };
}

/** Generates from the committed pin and used surface. */
export async function generateFromRepo(root: string = ROOT): Promise<Record<keyof typeof OUTPUTS, string>> {
  return generate(await readJson<Spec>(root, PINNED_SPEC), await readJson<UsedSurface>(root, USED_SURFACE));
}

if (import.meta.main) {
  const check = process.argv.includes("--check");
  const files = await generateFromRepo();
  let stale = false;
  for (const [key, path] of Object.entries(OUTPUTS) as [keyof typeof OUTPUTS, string][]) {
    const full = join(ROOT, path);
    if (check) {
      const current = await readFile(full, "utf8").catch(() => "");
      if (current !== files[key]) {
        console.error(`${path} is stale: run \`bun run gen:gc\``);
        stale = true;
      }
    } else {
      await writeFile(full, files[key]);
      console.log(`wrote ${path}`);
    }
  }
  if (stale) process.exit(1);
}
